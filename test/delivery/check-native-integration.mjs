await sessions.migrateLegacy(legacyCtx);
assert.deepEqual(archived,['old-session']);assert.deepEqual(removed,['old-workspace']);
assert.equal(sessions.get('old-session').legacySidebar,true);
await sessions.open(legacyCtx,'old-session');assert.deepEqual(archived,[]);
await sessions.hideLegacy(legacyCtx,'old-session');assert.deepEqual(archived,['old-session']);
